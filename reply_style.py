"""按心情 × 体力拼出 replyer 的 reply_style。

主程序把 ``global_config.personality.reply_style`` 填进
``prompts/zh-CN/maisaka_replyer.prompt`` 的 ``{reply_style}`` 占位符，本插件在
replyer hook 里把那一行**整段换掉**。是替换不是追加：原串里有「避免过度感叹」
这类禁令，追加解不开禁令，两串并存只会让模型在两个方向之间自己挑一个。

拼接顺序是 **口吻 → 体力 → 固定**。体力那句紧跟在口吻后面，接得上转折；
固定部分是通篇的底线要求，压在最后。

板块一（口吻）按心情三档走。板块二（这个口吻还剩多少输出）**先看心情再分体力，
三档心情各有各的一组**。早先试过让板块二只有三句、跟心情自由组合，读下来不搭——
同样是没力气，高兴时的没力气和不痛快时的没力气，在文字上不是一回事，一句通用的
覆盖不了。代价是九句各自独立，改一处不会传到别处，得手动对。

``frontend/viewer.py`` 直接 import 这个模块把表发到预览页，所以改这里前端跟着变，
不用两头核对。因此本模块**只用标准库**，不要引 maibot_sdk 或插件内的其它模块。
"""

MOODS = ("正面", "中性", "负面")
ENERGIES = ("良好", "一般", "不佳")

# 板块一：口吻本身。
VOICE = {
    "正面": "使用日常自然、可爱、甜美萌动的JK少女感口吻。",
    "中性": "使用日常自然的JK少女感口吻。",
    "负面": "使用带有一丝沮丧、委屈与失落感的JK少女感口吻。",
}

# 不随档位变的底线要求。原先这里还有「避免过度感叹和夸张表达。不要过分修辞和
# 复杂句。」，是从配置里那串继承下来的，后来删了——口吻和句子长短已经归板块一、
# 板块二管，那两句在九格里重复了一遍同样的事。
#
# 语气助词那条是**禁令加改道**：不只说别用，还指定那份情绪改走哪条路。原句
# 「不要加语气助词来软化」把禁令挂在动机上——留着「呀、啦、哦」再判定自己不是在
# 软化就绕过去了；而装可爱、示弱本来就是 Mittes 的底色，光禁不给出口，等于把角色
# 最像她的部分一起剪了。所以这一版给了替代通道。
#
# 改道的落点是**用词和内容**，不是标点。曾经写过「主要通过标点符号或文本风格来
# 表达」，实测翻车：省略号出现率从 4.9% 涨到 37.9%，末尾省略号从 3.4% 涨到 24.1%，
# 而波浪号一点没动（0.4% → 0%）。给一个类别，模型就挑这个类别里最便宜的那个实例
# 往死里用。**别再往这句里写标点符号、表情或任何字符级的通道**，要指就指大到
# 坍缩不了的东西。
#
# 顺带记一笔这个部署的标点现状：主程序会删掉每条消息末尾的中文句号
# （``remove_terminal_full_stop``），分段器切句时也丢掉切点的句号和逗号，只保留
# 问号、感叹号、省略号、波浪号，所以她 93.8% 的消息结尾本就没有标点。
FIXED = "句尾不随意添加语气助词，情绪主要通过用词和说话的内容来表达。"

# 板块二。三组各写各的——正面和中性眼下三句全都字面相同，但它们是**两张表**，
# 谁要改都不会牵动另一边。合并成一张的话，以后想只动正面就得先拆回来。
STAMINA = {
    "正面": {
        "良好": "说话直接坦荡，带着自然的温度和从容感。",
        "一般": "说话随性平缓，带着一丝懒散的日常感与淡淡的从容。",
        "不佳": "说话声音发软、会下意识地撒娇求安抚或小声哼唧。",
    },
    "中性": {
        "良好": "说话直接坦荡，带着自然的温度和从容感。",
        "一般": "说话随性平缓，带着一丝懒散的日常感与淡淡的从容。",
        "不佳": "说话声音发软、会下意识地撒娇求安抚或小声哼唧。",
    },
    "负面": {
        "良好": "说话直接，需要通过吐槽把内心的负面情绪宣泄出来。",
        "一般": "说话随性平缓，话语里全是沮丧、委屈或被逼无奈的叹气。",
        "不佳": "说话声音发软，断断续续，连说话都嫌累，听起来整个人蔫蔫的、毫无生气。",
    },
}


def compose(mood_level: str, energy_level: str) -> str:
    """拼出这一格的 reply_style；档位缺一个就返回空串。

    返回空串时调用方**什么都别做**，让主程序配置里那份原样留着。底稿段没有档位，
    那时候硬拼一个默认格子，等于拿中性的语气盖住一段本来就不知道她什么状态的时间。
    """
    voice = VOICE.get(mood_level.strip())
    stamina = STAMINA.get(mood_level.strip(), {}).get(energy_level.strip())
    if not voice or not stamina:
        return ""
    return f"{voice}{stamina}{FIXED}"
